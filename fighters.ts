type Input = {
  id: string;
  first: string;
  last: string;
  nickname?: string;
  division: Division;
  sex?: Sex;
  stance?: Stance;
  heightIn: number;
  reachIn: number;
  age: number;
  country: string;
  w: number;
  l: number;
  d?: number;
  nc?: number;
  ranking?: number | "C";
  koWins: number;
  subWins: number;
  decWins?: number;
  koLosses?: number;
  subLosses?: number;
  ratings: Partial<Ratings>;
  flags?: Fighter["flags"];
  notes?: string;
};

function isWomens(d: Division): boolean {
  return d.startsWith("womens-");
}

function make(p: Input): Fighter {
  const decWins = p.decWins ?? Math.max(0, p.w - p.koWins - p.subWins);
  return {
    id: p.id,
    first: p.first,
    last: p.last,
    nickname: p.nickname,
    division: p.division,
    sex: p.sex ?? (isWomens(p.division) ? "F" : "M"),
    stance: p.stance ?? "orthodox",
    heightIn: p.heightIn,
    reachIn: p.reachIn,
    age: p.age,
    country: p.country,
    record: { w: p.w, l: p.l, d: p.d ?? 0, nc: p.nc },
    ranking: p.ranking,
    koWins: p.koWins,
    subWins: p.subWins,
    decWins,
    koLosses: p.koLosses ?? 0,
    subLosses: p.subLosses ?? 0,
    ratings: { ...BASE, ...p.ratings },
    flags: p.flags,
    notes: p.notes,
  };
}


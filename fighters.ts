export const FIGHTER_BY_ID: Record<string, Fighter> = Object.fromEntries(
  FIGHTERS.map((f) => [f.id, f]),
);

export function fighterById(id: string): Fighter {
  const f = FIGHTER_BY_ID[id];
  if (!f) throw new Error(`Unknown fighter: ${id}`);
  return f;
}

export function displayName(f: Fighter): string {
  return `${f.first} ${f.last}`;
}

export function recordString(f: Fighter): string {
  return f.record.d ? `${f.record.w}-${f.record.l}-${f.record.d}` : `${f.record.w}-${f.record.l}`;
}

export function searchFighters(q: string): Fighter[] {
  const s = q.trim().toLowerCase();
  if (!s) return FIGHTERS;
  return FIGHTERS.filter((f) => {
    const blob = `${f.first} ${f.last} ${f.nickname ?? ""} ${f.country}`.toLowerCase();
    return blob.includes(s);
  });
}
